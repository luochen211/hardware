/* --- ADC通道定义（ESP32 ADC1通道→GPIO映射）---
 * ADC1_CH5 = GPIO33（雨滴）
 * ADC1_CH6 = GPIO34（土壤湿度）
 * ADC1_CH7 = GPIO35（光照）
 */
#define SOIL_ADC_CHANNEL   ADC_CHANNEL_6   /* GPIO34 */
#define LIGHT_ADC_CHANNEL  ADC_CHANNEL_7   /* GPIO35 */
#define RAIN_ADC_CHANNEL   ADC_CHANNEL_5   /* GPIO33 */

/* --- I2C OLED --- */
#define I2C_MASTER_SCL_IO  GPIO_NUM_19
#define I2C_MASTER_SDA_IO  GPIO_NUM_18
#define I2C_MASTER_NUM     I2C_NUM_0
#define I2C_MASTER_FREQ_HZ 100000
#define OLED_I2C_ADDR      0x3C

static adc_oneshot_unit_handle_t s_adc1_handle = NULL;

/* ============== ADC 初始化 ============== */
static void adc_init(void)
{
    adc_oneshot_unit_init_cfg_t init_config = { .unit_id = ADC_UNIT_1 };
    ESP_ERROR_CHECK(adc_oneshot_new_unit(&init_config, &s_adc1_handle));

    adc_oneshot_chan_cfg_t config = {
        .bitwidth = ADC_BITWIDTH_12,
        .atten    = ADC_ATTEN_DB_12,
    };
    /* 配置3个ADC通道 */
    ESP_ERROR_CHECK(adc_oneshot_config_channel(s_adc1_handle, SOIL_ADC_CHANNEL, &config));
    ESP_ERROR_CHECK(adc_oneshot_config_channel(s_adc1_handle, LIGHT_ADC_CHANNEL, &config));
    ESP_ERROR_CHECK(adc_oneshot_config_channel(s_adc1_handle, RAIN_ADC_CHANNEL, &config));
    ESP_LOGI(TAG, "ADC初始化: CH5(雨滴/GPIO33) CH6(土壤/GPIO34) CH7(光照/GPIO35)");
}

static int adc_read_avg(adc_channel_t ch)
{
    int sum = 0;
    for (int i = 0; i < 5; i++) {
        int raw;
        adc_oneshot_read(s_adc1_handle, ch, &raw);
        sum += raw;
        vTaskDelay(pdMS_TO_TICKS(5));
    }
    return sum / 5;
}

/* ============== I2C OLED (SSD1306) ============== */
static esp_err_t oled_write_cmd(uint8_t cmd)
{
    i2c_cmd_handle_t h = i2c_cmd_link_create();
    i2c_master_start(h);
    i2c_master_write_byte(h, (OLED_I2C_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(h, 0x00, true);
    i2c_master_write_byte(h, cmd, true);
    i2c_master_stop(h);
    esp_err_t ret = i2c_master_cmd_begin(I2C_MASTER_NUM, h, pdMS_TO_TICKS(1000));
    i2c_cmd_link_delete(h);
    return ret;
}

static esp_err_t oled_write_data(uint8_t data)
{
    i2c_cmd_handle_t h = i2c_cmd_link_create();
    i2c_master_start(h);
    i2c_master_write_byte(h, (OLED_I2C_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(h, 0x40, true);
    i2c_master_write_byte(h, data, true);
    i2c_master_stop(h);
    esp_err_t ret = i2c_master_cmd_begin(I2C_MASTER_NUM, h, pdMS_TO_TICKS(1000));
    i2c_cmd_link_delete(h);
    return ret;
}

static void oled_clear(void)
{
    for (uint8_t page = 0; page < 8; page++) {
        oled_write_cmd(0xB0 + page);
        oled_write_cmd(0x00);
        oled_write_cmd(0x10);
        for (int col = 0; col < 128; col++)
            oled_write_data(0x00);
    }
}

