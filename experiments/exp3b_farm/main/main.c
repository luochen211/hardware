static void oled_show_text(int line, const char *text)
{
    if (line < 0 || line > 7) return;
    oled_write_cmd(0xB0 + line);
    oled_write_cmd(0x00);
    oled_write_cmd(0x10);
    /* 先用空格填满整行（21字符 × 6列 = 126列），清除旧内容残留 */
    for (int i = 0; i < 21; i++) {
        for (int col = 0; col < 5; col++)
            oled_write_data(0x00);
        oled_write_data(0x00);
    }
    /* 回到行首，写入新内容 */
    oled_write_cmd(0xB0 + line);
    oled_write_cmd(0x00);
    oled_write_cmd(0x10);
    for (int i = 0; text[i] != '\0' && i < 21; i++) {
        char c = text[i];
        if (c < 32 || c > 126) c = ' ';
        uint8_t idx = c - 32;
        for (int col = 0; col < 5; col++)
            oled_write_data(font5x8[idx][col]);
        oled_write_data(0x00);
    }
}

static void oled_init(void)
{
    i2c_config_t conf = {
        .mode = I2C_MODE_MASTER,
        .sda_io_num = I2C_MASTER_SDA_IO,
        .scl_io_num = I2C_MASTER_SCL_IO,
        .sda_pullup_en = GPIO_PULLUP_ENABLE,
        .scl_pullup_en = GPIO_PULLUP_ENABLE,
        .master.clk_speed = I2C_MASTER_FREQ_HZ,
    };
    ESP_ERROR_CHECK(i2c_param_config(I2C_MASTER_NUM, &conf));
    ESP_ERROR_CHECK(i2c_driver_install(I2C_MASTER_NUM, conf.mode, 0, 0, 0));

    const uint8_t cmds[] = {0xAE,0x20,0x00,0x40,0x81,0xCF,0xA1,0xA8,0x3F,
                            0xC8,0xD3,0x00,0xD5,0x80,0xD9,0xF1,0xDA,0x12,
                            0xDB,0x40,0x8D,0x14,0xA4,0xA6,0xAF};
    for (int i = 0; i < sizeof(cmds); i++)
        oled_write_cmd(cmds[i]);
    oled_clear();
    ESP_LOGI(TAG, "OLED初始化: SCL=GPIO19 SDA=GPIO18");
}

/* ============== app_main ============== */
void app_main(void)
{
    ESP_LOGI(TAG, "============================");
    ESP_LOGI(TAG, "实验3B: 智慧农业板 土壤+光照+雨滴+OLED");
    ESP_LOGI(TAG, "学号: %s  姓名: %s", STUDENT_ID, STUDENT_NAME);
    ESP_LOGI(TAG, "============================");

    adc_init();
    oled_init();

    oled_show_text(0, "IoT Smart Farm");
    oled_show_text(1, "Starting...");
    vTaskDelay(pdMS_TO_TICKS(1000));

    int loop = 0;
    while (1) {
        loop++;

        int soil = adc_read_avg(SOIL_ADC_CHANNEL);
        int light = adc_read_avg(LIGHT_ADC_CHANNEL);
        int rain = adc_read_avg(RAIN_ADC_CHANNEL);

        ESP_LOGI(TAG, "--- 采集#%d ---", loop);
        ESP_LOGI(TAG, "土壤湿度: ADC=%d", soil);
        ESP_LOGI(TAG, "光照: ADC=%d", light);
        ESP_LOGI(TAG, "雨滴: ADC=%d", rain);

        char buf[20];

        snprintf(buf, sizeof(buf), "Soil:%d", soil);
        oled_show_text(0, buf);

        snprintf(buf, sizeof(buf), "Light:%d", light);
        oled_show_text(1, buf);

        snprintf(buf, sizeof(buf), "Rain:%d", rain);
        oled_show_text(2, buf);

        snprintf(buf, sizeof(buf), "Loop:%d", loop);
        oled_show_text(3, buf);

        vTaskDelay(pdMS_TO_TICKS(2000));
    }
}
